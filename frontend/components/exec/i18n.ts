export type ExecKey = keyof Dict;

/** Teks modul eksekutif menurut bahasa aktif. */
export function useExecT() {
  const { locale } = useT();
  const d = locale === 'en' ? EN : ID;
  return (key: ExecKey, params?: Record<string, string | number>) => {
    let s: string = d[key] ?? ID[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

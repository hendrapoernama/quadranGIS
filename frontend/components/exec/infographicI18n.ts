export type InfoKey = keyof Dict;

/** Teks infografis menurut bahasa aktif. */
export function useInfoT() {
  const { locale } = useT();
  const d = locale === 'en' ? EN : ID;
  return (key: InfoKey | string, params?: Record<string, string | number>) => {
    let s: string = (d as Record<string, string>)[key] ?? (ID as Record<string, string>)[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

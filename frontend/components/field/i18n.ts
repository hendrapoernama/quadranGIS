export type FieldKey = keyof Dict;

export function useFieldT() {
  const { locale } = useT();
  const d = locale === 'en' ? EN : ID;
  return (key: FieldKey, params?: Record<string, string | number>) => {
    let s: string = d[key] ?? ID[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

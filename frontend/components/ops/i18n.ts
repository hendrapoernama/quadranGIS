export type OpsKey = keyof Dict;

/** Teks fitur operasi menurut bahasa aktif. */
export function useOpsT() {
  const { locale } = useT();
  const d = locale === 'en' ? EN : ID;
  return (key: OpsKey | string, params?: Record<string, string | number>) => {
    let s = (d as Record<string, string>)[key] ?? (ID as Record<string, string>)[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}
